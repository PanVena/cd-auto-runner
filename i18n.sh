cdar_detect_lang() {
  local v
  for v in "${LC_ALL:-}" "${LC_MESSAGES:-}" "${LANG:-}"; do
    [[ -n "$v" ]] || continue
    [[ "${v,,}" == uk* ]] && echo uk || echo en
    return 0
  done
  echo en
}

