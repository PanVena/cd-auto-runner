  if [[ "${CDAR_UI_LANG:-uk}" == en && -n "${CDAR_EN[$s]+x}" ]]; then s="${CDAR_EN[$s]}"; fi
  if (($#)); then printf -- "$s" "$@"; else printf '%s' "$s"; fi
}

